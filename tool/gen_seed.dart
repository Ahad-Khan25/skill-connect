// Generates supabase/seed.sql from lib/data/sample_data.dart so the fake
// backend and the database always contain the same sample students and open teams.
//   dart run tool/gen_seed.dart
import 'dart:io';

import 'package:teamup/data/sample_data.dart';

String q(String s) => "'${s.replaceAll("'", "''")}'";
String arr(List<String> l) => l.isEmpty ? "'{}'::text[]" : 'array[${l.map(q).join(', ')}]';

void main() {
  final b = StringBuffer()
    ..writeln('-- GENERATED by tool/gen_seed.dart from lib/data/sample_data.dart – do not edit by hand.')
    ..writeln('-- Sample students (user_id NULL, is_sample TRUE) + 5 open teams. Safe to re-run.')
    ..writeln('insert into public.profiles')
    ..writeln('  (id, name, university, department, semester, project_type, skills, interests, skills_needed, availability, work_experience, bio, is_sample)')
    ..writeln('values');
  final rows = kSampleProfiles.map((p) => '  (${q(p.id)}, ${q(p.name)}, ${q(p.university)}, ${q(p.department)}, ${p.semester}, '
      '${q(p.projectType)}, ${arr(p.skills)}, ${arr(p.interests)}, ${arr(p.skillsNeeded)}, '
      '${arr(p.availability)}, ${q(p.workExperience)}, ${q(p.bio)}, true)');
  b
    ..writeln(rows.join(',\n'))
    ..writeln('on conflict (id) do update set')
    ..writeln('  name = excluded.name, university = excluded.university, department = excluded.department, semester = excluded.semester,')
    ..writeln('  project_type = excluded.project_type, skills = excluded.skills, interests = excluded.interests,')
    ..writeln('  skills_needed = excluded.skills_needed, availability = excluded.availability,')
    ..writeln('  work_experience = excluded.work_experience, bio = excluded.bio, is_sample = true;')
    ..writeln();

  final teams = buildSampleOpenTeams();
  if (teams.isNotEmpty) {
    b
      ..writeln('insert into public.teams')
      ..writeln('  (id, owner_profile, title, description, project_type, roles_needed, required_skills, domain_tags)')
      ..writeln('values');
    final teamRows = teams.map((t) {
      final ownerId = t.owner?.profile.id ?? t.members.first.profile.id;
      return '  (${q(t.id)}, ${q(ownerId)}, ${q(t.title)}, ${q(t.description)}, ${q(t.projectType)}, '
          '${arr(t.openRoles)}, ${arr(t.requiredSkills)}, ${arr(t.domainTags)})';
    });
    b
      ..writeln(teamRows.join(',\n'))
      ..writeln('on conflict (id) do update set')
      ..writeln('  title = excluded.title, description = excluded.description, project_type = excluded.project_type,')
      ..writeln('  roles_needed = excluded.roles_needed, required_skills = excluded.required_skills, domain_tags = excluded.domain_tags;')
      ..writeln();

    b
      ..writeln('insert into public.team_members (team_id, profile_id, role)')
      ..writeln('values');
    final memberRows = <String>[];
    for (final t in teams) {
      for (final m in t.members) {
        memberRows.add('  (${q(t.id)}, ${q(m.profile.id)}, ${q(m.role)})');
      }
    }
    b
      ..writeln(memberRows.join(',\n'))
      ..writeln('on conflict (team_id, profile_id) do update set role = excluded.role;');
  }

  File('supabase/seed.sql').writeAsStringSync(b.toString());
  stdout.writeln('Wrote supabase/seed.sql (${kSampleProfiles.length} profiles, ${teams.length} open teams)');
}
