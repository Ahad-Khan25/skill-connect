// Generates supabase/seed.sql from lib/data/sample_data.dart so the fake
// backend and the database always contain the same sample students.
//   dart run tool/gen_seed.dart
import 'dart:io';

import 'package:teamup/data/sample_data.dart';

String q(String s) => "'${s.replaceAll("'", "''")}'";
String arr(List<String> l) => l.isEmpty ? "'{}'::text[]" : 'array[${l.map(q).join(', ')}]';

void main() {
  final b = StringBuffer()
    ..writeln('-- GENERATED by tool/gen_seed.dart from lib/data/sample_data.dart – do not edit by hand.')
    ..writeln('-- Sample students (user_id NULL, is_sample TRUE). Safe to re-run.')
    ..writeln('insert into public.profiles')
    ..writeln('  (id, name, department, semester, project_type, skills, interests, skills_needed, availability, bio, is_sample)')
    ..writeln('values');
  final rows = kSampleProfiles.map((p) => '  (${q(p.id)}, ${q(p.name)}, ${q(p.department)}, ${p.semester}, '
      '${q(p.projectType)}, ${arr(p.skills)}, ${arr(p.interests)}, ${arr(p.skillsNeeded)}, '
      '${arr(p.availability)}, ${q(p.bio)}, true)');
  b
    ..writeln(rows.join(',\n'))
    ..writeln('on conflict (id) do update set')
    ..writeln('  name = excluded.name, department = excluded.department, semester = excluded.semester,')
    ..writeln('  project_type = excluded.project_type, skills = excluded.skills, interests = excluded.interests,')
    ..writeln('  skills_needed = excluded.skills_needed, availability = excluded.availability,')
    ..writeln('  bio = excluded.bio, is_sample = true;');
  File('supabase/seed.sql').writeAsStringSync(b.toString());
  stdout.writeln('Wrote supabase/seed.sql (${kSampleProfiles.length} profiles)');
}
